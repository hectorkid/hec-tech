const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('hec-multi-photos.js','utf8');
const enhance=source.slice(source.indexOf('function enhanceCards()'),source.indexOf('function attach()'));
let reads=0,seen=[];
const inventory=Array.from({length:500},(_,i)=>({id:i+1,image:'photo-'+i}));
let cards=inventory.map(x=>({dataset:{},getAttribute:()=>`detail(${x.id})`}));
const grid={querySelectorAll:()=>cards};
const context={document:{getElementById:()=>grid},localStorage:{getItem(){reads++;return JSON.stringify(inventory)}},key:'inventory',photos:x=>{seen.push(x.id);return [x.image]},Map};
vm.runInNewContext(enhance+';enhanceCards()',context);
assert.equal(reads,1,'500 cards must read and parse the inventory once');
assert.equal(seen.length,500);assert.equal(new Set(seen).size,500);
cards=cards.map(x=>({...x,dataset:{hecCardGallery:'1'}}));reads=0;
vm.runInNewContext(enhance+';enhanceCards()',context);assert.equal(reads,0,'Already enhanced cards need no inventory read');
const dashboard=fs.readFileSync('hec-v3.js','utf8');
const counts=dashboard.slice(dashboard.indexOf('const categoryCounts='),dashboard.indexOf('const saved='));
let classifications=0,writes=0;
const categories=['Power Tools','Home & Kitchen','Other'];
const elements=categories.map(category=>({dataset:{hecCatCount:category},get textContent(){return this.label||''},set textContent(v){writes++;this.label=v}}));
const data={active:inventory,Map,bucket:item=>{classifications++;return categories[item.id%3]},document:{querySelectorAll:()=>elements}};
vm.runInNewContext(counts,data);assert.equal(classifications,500,'Classify each item once across all category counts');
assert.equal(elements.reduce((n,e)=>n+parseInt(e.textContent),0),500);
classifications=0;writes=0;vm.runInNewContext('(function(){'+counts+'})()',data);assert.equal(writes,0,'Unchanged category counts must not rewrite the DOM');
console.log('500-item efficiency checks passed: one inventory read and one classification per item');
